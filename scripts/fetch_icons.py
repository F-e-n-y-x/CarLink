# Directional glyphs mirror in RTL layouts (DESIGN_SPEC §7.3); device and media glyphs do not.
AUTO_MIRRORED = {"arrow_back", "arrow_forward", "chevron_right", "open_in_new", "ios_share"}

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded "{name}" ({style}), Apache License 2.0. Generated by scripts/fetch_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960"{mirror}
    android:tint="?android:attr/colorControlNormal">
    <group android:translateY="960">
        <path
            android:fillColor="@android:color/white"
            android:pathData="{path}" />
    </group>
</vector>
"""


def fetch(name: str, style: str) -> str:
    with urllib.request.urlopen(URL.format(name=name, style=style), timeout=30) as response:
        svg = response.read().decode("utf-8")
    if 'viewBox="0 -960 960 960"' not in svg:
        raise ValueError(f"{name}/{style}: unexpected viewBox")
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
    if len(paths) != 1 or not re.fullmatch(r"[0-9MmLlHhVvCcSsQqTtAaZz.,\s-]+", paths[0]):
        raise ValueError(f"{name}/{style}: expected one plain path")
    return paths[0]


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    failures = []
    for name, filled in ICONS.items():
        for style, suffix in [("default", "")] + ([("fill1", "_filled")] if filled else []):
            try:
                path = fetch(name, style)
            except Exception as error:  # noqa: BLE001 - report every missing glyph at the end
                failures.append(f"{name}/{style}: {error}")
                continue
            mirror = '\n    android:autoMirrored="true"' if name in AUTO_MIRRORED else ""
            (OUT / f"carlink_ic_{name}{suffix}.xml").write_text(
                TEMPLATE.format(name=name, style=style, mirror=mirror, path=path))
    for failure in failures:
        print("failed:", failure, file=sys.stderr)
    print(f"{len(ICONS)} icons, {len(failures)} failures")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
