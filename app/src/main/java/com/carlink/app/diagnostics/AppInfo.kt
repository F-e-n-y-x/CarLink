package com.carlink.app.diagnostics

import android.content.Context
import android.hardware.display.DisplayManager
import android.os.Build
import android.util.DisplayMetrics
import android.view.Display
import com.carlink.app.BuildConfig

/** Versions and device facts for About and diagnostic reports. */
object AppInfo {
    val versionName: String get() = BuildConfig.VERSION_NAME
    val versionCode: Int get() = BuildConfig.VERSION_CODE

    /** DiPlay's version, read from vendor/diplay at build time (see app/build.gradle.kts). */
    val carPlayEngineVersion: String get() = BuildConfig.DIPLAY_VERSION_NAME

    /** DiAuto's version, from the Android Auto engine library's own BuildConfig. */
    val androidAutoEngineVersion: String get() = com.andrerinas.openheadunit.BuildConfig.VERSION_NAME

    val manufacturer: String get() = Build.MANUFACTURER.orEmpty().replaceFirstChar { it.titlecase() }
    val model: String get() = Build.MODEL.orEmpty()
    val androidRelease: String get() = Build.VERSION.RELEASE.orEmpty()

    /** The panel's full size in pixels (not the app window), landscape-first as head units list it. */
    @Suppress("DEPRECATION") // getRealMetrics is the API-25-compatible way to read the panel size.
    fun screenPixels(context: Context): Pair<Int, Int> {
        val display = context.getSystemService(DisplayManager::class.java)?.getDisplay(Display.DEFAULT_DISPLAY)
        val metrics = DisplayMetrics()
        if (display != null) display.getRealMetrics(metrics) else metrics.setTo(context.resources.displayMetrics)
        return metrics.widthPixels to metrics.heightPixels
    }

    /** Where the source of each engine is published; CarLink's own repository is added when public. */
    const val CARPLAY_ENGINE_SOURCE = "https://github.com/shihabal3amri/DiPlay"
    const val ANDROID_AUTO_ENGINE_SOURCE = "https://github.com/shihabal3amri/DiAuto"

    /** License texts in the APK assets (the first two are generated by app/build.gradle.kts). */
    const val AGPL_ASSET = "carlink-licenses/AGPL-3.0.txt"
    const val GPL_ASSET = "carlink-licenses/GPL-3.0.txt"
    const val BYDMATE_ASSET = "byd-hud-icons/LICENSE-BYDMate.txt"

    /** Reads a bundled text asset, or null when this build doesn't include it. Call off the main thread. */
    fun readAsset(context: Context, path: String): String? = runCatching {
        context.assets.open(path).bufferedReader().use { it.readText() }
    }.getOrNull()

    /**
     * Splits a plain-text license into paragraphs and rejoins hard-wrapped lines, so the text
     * reflows at any width and font scale instead of keeping its 80-column breaks.
     */
    fun paragraphs(text: String): List<String> =
        text.replace("\r\n", "\n").split(Regex("\n\\s*\n"))
            .map { block -> block.lines().joinToString(" ") { it.trim() }.trim() }
            .filter { it.isNotEmpty() }
}
